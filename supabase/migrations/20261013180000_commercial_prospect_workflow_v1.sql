create or replace function public.has_prospect_management()
returns boolean language sql stable security definer
set search_path = public, pg_temp
as $$
  select public.is_internal_user()
    and exists (select 1 from public.commercial_user_permissions cp
                where cp.user_id=(select auth.uid()) and cp.manage_prospects);
$$;
revoke all on function public.has_prospect_management() from public, anon, authenticated;
grant execute on function public.has_prospect_management() to authenticated;

create or replace function public.set_prospect_management(p_user_id uuid, p_enabled boolean)
returns void language plpgsql security definer
set search_path = public, pg_temp
as $$
begin
  if not exists (select 1 from public.profiles p where p.id=(select auth.uid()) and p.active and p.is_master)
     or not public.is_internal_user() then
    raise exception 'PROSPECT_PERMISSION_ADMIN_REQUIRED' using errcode='42501';
  end if;
  if not exists (select 1 from public.profiles p where p.id=p_user_id and p.active)
     or exists (select 1 from public.client_portal_users cpu where cpu.user_id=p_user_id and cpu.active) then
    raise exception 'PROSPECT_PERMISSION_TARGET_INVALID' using errcode='22023';
  end if;
  insert into public.commercial_user_permissions(user_id,manage_prospects,granted_by,granted_at,updated_at)
  values(p_user_id,p_enabled,case when p_enabled then auth.uid() else null end,
    case when p_enabled then now() else null end,now())
  on conflict(user_id) do update set manage_prospects=excluded.manage_prospects,
    granted_by=excluded.granted_by,granted_at=excluded.granted_at,updated_at=now();
end;
$$;
revoke all on function public.set_prospect_management(uuid,boolean) from public, anon, authenticated;
grant execute on function public.set_prospect_management(uuid,boolean) to authenticated;

