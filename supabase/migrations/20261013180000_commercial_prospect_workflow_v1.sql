create or replace function public.record_prospect_event()
returns trigger language plpgsql security definer
set search_path = public, pg_temp
as $$
declare v_event text; v_details jsonb;
begin
  if tg_op='INSERT' then
    v_event := 'created';
    v_details := jsonb_build_object('status',new.status,'source',new.source,'owner_id',new.owner_id);
    insert into public.prospect_events(prospect_id,actor_id,event_type,details)
    values(new.id,auth.uid(),v_event,v_details);
    return new;
  end if;
  if row(new.status,new.owner_id,new.source,new.last_contact_at,new.customer_statement,
         new.commercial_perception,new.next_action,new.next_review_at,new.next_condition,
         new.pause_reason,new.pause_until,new.closed_reason)
     is distinct from
     row(old.status,old.owner_id,old.source,old.last_contact_at,old.customer_statement,
         old.commercial_perception,old.next_action,old.next_review_at,old.next_condition,
         old.pause_reason,old.pause_until,old.closed_reason) then
    v_event := case when old.status is distinct from new.status then 'status_changed'
                    when old.owner_id is distinct from new.owner_id then 'assignment_changed'
                    else 'updated' end;
    v_details := jsonb_build_object(
      'before',jsonb_build_object('status',old.status,'owner_id',old.owner_id,'source',old.source,
        'last_contact_at',old.last_contact_at,'customer_statement',old.customer_statement,
        'commercial_perception',old.commercial_perception,'next_action',old.next_action,
        'next_review_at',old.next_review_at,'next_condition',old.next_condition,
        'pause_reason',old.pause_reason,'pause_until',old.pause_until,'closed_reason',old.closed_reason),
      'after',jsonb_build_object('status',new.status,'owner_id',new.owner_id,'source',new.source,
        'last_contact_at',new.last_contact_at,'customer_statement',new.customer_statement,
        'commercial_perception',new.commercial_perception,'next_action',new.next_action,
        'next_review_at',new.next_review_at,'next_condition',new.next_condition,
        'pause_reason',new.pause_reason,'pause_until',new.pause_until,'closed_reason',new.closed_reason));
    insert into public.prospect_events(prospect_id,actor_id,event_type,details)
    values(new.id,auth.uid(),v_event,v_details);
  end if;
  return new;
end;
$$;
revoke all on function public.record_prospect_event() from public, anon, authenticated;
drop trigger if exists trg_record_prospect_event on public.prospects;
create trigger trg_record_prospect_event after insert or update on public.prospects
for each row execute function public.record_prospect_event();

create or replace function public.record_prospect_need_event()
returns trigger language plpgsql security definer
set search_path = public, pg_temp
as $$
declare v_prospect uuid; v_event text; v_details jsonb;
begin
  v_prospect:=case when tg_op='DELETE' then old.prospect_id else new.prospect_id end;
  v_event:=case when tg_op='INSERT' then 'need_added' when tg_op='UPDATE' then 'need_updated' else 'need_removed' end;
  v_details:=case when tg_op='DELETE' then jsonb_build_object('category',old.category,'service_description',old.service_description)
    else jsonb_build_object('category',new.category,'service_description',new.service_description) end;
  insert into public.prospect_events(prospect_id,actor_id,event_type,details)
  values(v_prospect,auth.uid(),v_event,v_details);
  if tg_op='DELETE' then return old; end if;
  return new;
end;
$$;
revoke all on function public.record_prospect_need_event() from public, anon, authenticated;
drop trigger if exists trg_record_prospect_need_event on public.prospect_needs;
create trigger trg_record_prospect_need_event after insert or update or delete on public.prospect_needs
for each row execute function public.record_prospect_need_event();

create or replace function public.record_prospect_identity_event()
returns trigger language plpgsql security definer
set search_path = public, pg_temp
as $$
begin
  if row(old.entity_type,old.display_name,old.legal_name,old.tax_id,old.email,old.phone)
     is distinct from row(new.entity_type,new.display_name,new.legal_name,new.tax_id,new.email,new.phone) then
    insert into public.prospect_events(prospect_id,actor_id,event_type,details)
    select p.id,auth.uid(),'identity_updated',jsonb_build_object(
      'before',jsonb_build_object('entity_type',old.entity_type,'display_name',old.display_name,
        'legal_name',old.legal_name,'tax_id',old.tax_id,'email',old.email,'phone',old.phone),
      'after',jsonb_build_object('entity_type',new.entity_type,'display_name',new.display_name,
        'legal_name',new.legal_name,'tax_id',new.tax_id,'email',new.email,'phone',new.phone))
    from public.prospects p where p.commercial_entity_id=new.id;
  end if;
  return new;
end;
$$;
revoke all on function public.record_prospect_identity_event() from public, anon, authenticated;
drop trigger if exists trg_record_prospect_identity_event on public.commercial_entities;
create trigger trg_record_prospect_identity_event after update on public.commercial_entities
for each row execute function public.record_prospect_identity_event();

create or replace function public.find_prospect_identity_matches(
  p_entity_type text, p_display_name text, p_tax_id text, p_email text, p_phone text
)
returns table(id uuid,display_name text,entity_type text,legal_name text,tax_id text,email text,phone text)
language plpgsql stable security invoker set search_path=public
as $$
begin
  if not public.is_internal_user() then raise exception 'INTERNAL_ACCESS_REQUIRED' using errcode='42501'; end if;
  return query select ce.id,ce.display_name,ce.entity_type,ce.legal_name,ce.tax_id,ce.email,ce.phone
  from public.commercial_entities ce
  where ce.archived_at is null and (
    (nullif(btrim(p_tax_id),'') is not null and regexp_replace(lower(ce.tax_id),'[^[:alnum:]]','','g')=regexp_replace(lower(btrim(p_tax_id)),'[^[:alnum:]]','','g')) or
    (nullif(btrim(p_email),'') is not null and lower(btrim(ce.email))=lower(btrim(p_email))) or
    (nullif(btrim(p_phone),'') is not null and regexp_replace(ce.phone,'[^0-9]','','g')=regexp_replace(p_phone,'[^0-9]','','g')) or
    (length(btrim(coalesce(p_display_name,'')))>=4 and ce.entity_type=p_entity_type and
      (position(lower(btrim(p_display_name)) in lower(btrim(ce.display_name)))>0
       or position(lower(btrim(ce.display_name)) in lower(btrim(p_display_name)))>0))
  ) order by ce.created_at limit 10;
end;
$$;
revoke all on function public.find_prospect_identity_matches(text,text,text,text,text) from public, anon, authenticated;
grant execute on function public.find_prospect_identity_matches(text,text,text,text,text) to authenticated;

create or replace function public.save_prospect(
  p_prospect_id uuid,
  p_entity_id uuid,
  p_entity jsonb,
  p_prospect jsonb,
  p_needs jsonb default '[]'::jsonb,
  p_allow_duplicate_identity boolean default false
)
returns uuid language plpgsql security definer set search_path=public,pg_temp
as $$
declare v_actor uuid := (select auth.uid()); v_entity uuid:=p_entity_id; v_id uuid:=p_prospect_id;
  v_status text; v_owner uuid; v_next text; v_when timestamptz; v_condition text;
  v_need jsonb; v_type text;
  v_old_status text; v_pause_until timestamptz;
begin
  if not public.has_prospect_management() then raise exception 'PROSPECT_MANAGEMENT_REQUIRED' using errcode='42501'; end if;
  if p_entity is null or p_prospect is null or jsonb_typeof(coalesce(p_needs,'[]'::jsonb))<>'array' then
    raise exception 'PROSPECT_PAYLOAD_INVALID' using errcode='22023';
  end if;
  if nullif(btrim(p_entity->>'display_name'),'') is null then raise exception 'PROSPECT_NAME_REQUIRED' using errcode='22023'; end if;
  v_type:=p_entity->>'entity_type';
  if v_type not in ('company','person') then raise exception 'PROSPECT_ENTITY_TYPE_INVALID' using errcode='22023'; end if;
  v_status:=coalesce(nullif(p_prospect->>'status',''),'new');
  if v_status not in ('new','contacted','qualifying','converted','paused','disqualified') then raise exception 'PROSPECT_STATUS_INVALID' using errcode='22023'; end if;
  if v_status='converted' then raise exception 'PROSPECT_CONVERSION_FUNCTION_REQUIRED' using errcode='42501'; end if;
  v_owner:=nullif(p_prospect->>'owner_id','')::uuid;
  if v_owner is not null and not exists (select 1 from public.profiles p where p.id=v_owner and p.active)
     then raise exception 'PROSPECT_OWNER_INVALID' using errcode='22023'; end if;
  if v_owner is not null and exists(select 1 from public.client_portal_users cpu where cpu.user_id=v_owner and cpu.active)
     then raise exception 'PROSPECT_OWNER_INVALID' using errcode='22023'; end if;
  if v_status='paused' and nullif(btrim(p_prospect->>'pause_reason'),'') is null then raise exception 'PROSPECT_PAUSE_REASON_REQUIRED' using errcode='22023'; end if;
  v_next:=nullif(btrim(p_prospect->>'next_action'),'');
  v_when:=nullif(p_prospect->>'next_review_at','')::timestamptz;
  v_condition:=nullif(btrim(p_prospect->>'next_condition'),'');
  v_pause_until:=nullif(p_prospect->>'pause_until','')::timestamptz;
  if v_status='paused' then
    v_next:=coalesce(v_next,'Revisar Prospecto pausado');
    v_when:=coalesce(v_when,v_pause_until);
    v_condition:=coalesce(v_condition,case when v_when is null then 'Revisar cuando exista nueva información' end);
  end if;
  if v_status not in ('disqualified','converted') and v_next is null then
    raise exception 'PROSPECT_CONTINUITY_ACTION_REQUIRED' using errcode='22023';
  end if;
  if v_next is not null and v_when is null and v_condition is null then raise exception 'PROSPECT_CONTINUITY_REQUIRED' using errcode='22023'; end if;
  if v_next is null and (v_when is not null or v_condition is not null) then raise exception 'PROSPECT_CONTINUITY_ACTION_REQUIRED' using errcode='22023'; end if;
  if p_prospect_id is not null then
    select status into v_old_status from public.prospects where id=p_prospect_id and commercial_entity_id=p_entity_id and archived_at is null for update;
    if not found then raise exception 'PROSPECT_NOT_FOUND_OR_FORBIDDEN' using errcode='42501'; end if;
    if v_old_status='converted' then raise exception 'PROSPECT_ALREADY_CONVERTED' using errcode='22023'; end if;
    if v_old_status='paused' and v_status<>'paused' and v_next is null then
      raise exception 'PROSPECT_REACTIVATION_NEXT_STEP_REQUIRED' using errcode='22023';
    end if;
    if not exists(select 1 from public.prospects p where p.id=p_prospect_id and p.commercial_entity_id=p_entity_id and p.archived_at is null) then
      raise exception 'PROSPECT_NOT_FOUND_OR_FORBIDDEN' using errcode='42501';
    end if;
    update public.commercial_entities set entity_type=v_type,display_name=btrim(p_entity->>'display_name'),
      legal_name=nullif(btrim(p_entity->>'legal_name'),''),tax_id=nullif(btrim(p_entity->>'tax_id'),''),
      email=nullif(btrim(p_entity->>'email'),''),phone=nullif(btrim(p_entity->>'phone'),''),updated_at=now()
      where id=p_entity_id and legacy_client_id is null
        and not exists(select 1 from public.clients c where c.commercial_entity_id=public.commercial_entities.id);
    if not found then raise exception 'PROSPECT_IDENTITY_IS_LEGACY_OR_CLIENT' using errcode='42501'; end if;
    update public.prospects set status=v_status,owner_id=v_owner,
      source=nullif(btrim(p_prospect->>'source'),''),source_other=nullif(btrim(p_prospect->>'source_other'),''),
      last_contact_at=nullif(p_prospect->>'last_contact_at','')::timestamptz,
      customer_statement=nullif(btrim(p_prospect->>'customer_statement'),''),
      commercial_perception=nullif(btrim(p_prospect->>'commercial_perception'),''),
      next_action=v_next,next_review_at=v_when,
      next_condition=v_condition,pause_reason=nullif(btrim(p_prospect->>'pause_reason'),''),
      pause_until=v_pause_until,
      closed_reason=nullif(btrim(p_prospect->>'closed_reason'),''),updated_at=now()
      where id=p_prospect_id returning id into v_id;
    delete from public.prospect_needs where prospect_id=v_id;
  else
    if v_entity is null then
      if nullif(btrim(p_entity->>'tax_id'),'') is not null then perform pg_advisory_xact_lock(hashtextextended('tax:'||regexp_replace(lower(btrim(p_entity->>'tax_id')),'[^[:alnum:]]','','g'),0)); end if;
      if nullif(btrim(p_entity->>'email'),'') is not null then perform pg_advisory_xact_lock(hashtextextended('email:'||lower(btrim(p_entity->>'email')),0)); end if;
      if nullif(btrim(p_entity->>'phone'),'') is not null then perform pg_advisory_xact_lock(hashtextextended('phone:'||regexp_replace(p_entity->>'phone','[^0-9]','','g'),0)); end if;
      if nullif(btrim(p_entity->>'display_name'),'') is not null then perform pg_advisory_xact_lock(hashtextextended('name:'||v_type||':'||lower(btrim(p_entity->>'display_name')),0)); end if;
      if exists(select 1 from public.commercial_entities ce where ce.archived_at is null and
        nullif(btrim(p_entity->>'tax_id'),'') is not null and
        regexp_replace(lower(ce.tax_id),'[^[:alnum:]]','','g')=regexp_replace(lower(btrim(p_entity->>'tax_id')),'[^[:alnum:]]','','g')) then
        raise exception 'PROSPECT_TAX_ID_ALREADY_REGISTERED' using errcode='23505';
      end if;
      if not p_allow_duplicate_identity and exists(select 1 from public.commercial_entities ce where ce.archived_at is null and (
        (nullif(btrim(p_entity->>'email'),'') is not null and lower(btrim(ce.email))=lower(btrim(p_entity->>'email'))) or
        (nullif(btrim(p_entity->>'phone'),'') is not null and regexp_replace(ce.phone,'[^0-9]','','g')=regexp_replace(p_entity->>'phone','[^0-9]','','g')) or
        (lower(btrim(ce.display_name))=lower(btrim(p_entity->>'display_name')) and ce.entity_type=v_type))) then
        raise exception 'PROSPECT_POSSIBLE_DUPLICATE' using errcode='23505';
      end if;
      insert into public.commercial_entities(entity_type,display_name,legal_name,tax_id,email,phone,created_by)
      values(v_type,btrim(p_entity->>'display_name'),nullif(btrim(p_entity->>'legal_name'),''),
        nullif(btrim(p_entity->>'tax_id'),''),nullif(btrim(p_entity->>'email'),''),nullif(btrim(p_entity->>'phone'),''),v_actor)
      returning id into v_entity;
    else
      if not exists(select 1 from public.commercial_entities ce where ce.id=v_entity and ce.archived_at is null) then
        raise exception 'PROSPECT_IDENTITY_NOT_FOUND' using errcode='22023';
      end if;
    end if;
    insert into public.prospects(commercial_entity_id,status,owner_id,source,source_other,created_by,
      referrer_id,last_contact_at,customer_statement,commercial_perception,next_action,next_review_at,
      next_condition,pause_reason,pause_until,closed_reason)
    values(v_entity,v_status,v_owner,nullif(btrim(p_prospect->>'source'),''),
      nullif(btrim(p_prospect->>'source_other'),''),v_actor,nullif(p_prospect->>'referrer_id','')::uuid,
      nullif(p_prospect->>'last_contact_at','')::timestamptz,nullif(btrim(p_prospect->>'customer_statement'),''),
      nullif(btrim(p_prospect->>'commercial_perception'),''),v_next,v_when,v_condition,
      nullif(btrim(p_prospect->>'pause_reason'),''),v_pause_until,
      nullif(btrim(p_prospect->>'closed_reason'),'')) returning id into v_id;
  end if;
  for v_need in select value from jsonb_array_elements(coalesce(p_needs,'[]'::jsonb)) loop
    if nullif(btrim(v_need->>'service_description'),'') is not null then
      insert into public.prospect_needs(prospect_id,catalog_item_id,category,service_description,catalog_label_snapshot)
      values(v_id,nullif(v_need->>'catalog_item_id','')::uuid,nullif(btrim(v_need->>'category'),''),
        btrim(v_need->>'service_description'),nullif(btrim(v_need->>'catalog_label_snapshot'),''));
    end if;
  end loop;
  if v_next is not null then
    insert into public.radar_items(source_type,source_id,responsible_id,state,next_action,next_review_at,
      condition_text,last_movement_at,updated_at)
    values('prospect',v_id,v_owner,'active',v_next,v_when,v_condition,now(),now())
    on conflict (source_type,source_id) where state='active'
    do update set responsible_id=excluded.responsible_id,next_action=excluded.next_action,
      next_review_at=excluded.next_review_at,condition_text=excluded.condition_text,
      last_movement_at=now(),updated_at=now(),closed_at=null;
  elsif v_status='disqualified' then
    update public.radar_items set state='closed',closed_at=now(),updated_at=now(),last_movement_at=now()
    where source_type='prospect' and source_id=v_id and state='active';
  else
    update public.radar_items set state='closed',closed_at=now(),updated_at=now(),last_movement_at=now()
    where source_type='prospect' and source_id=v_id and state='active';
  end if;
  return v_id;
end;
$$;
