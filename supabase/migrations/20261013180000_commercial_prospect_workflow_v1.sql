-- Narrow conversion endpoint: exposes only the new Opportunity UUID, not the
-- protected opportunity row or its financial fields. Human confirmation is mandatory.
create or replace function public.convert_prospect_to_opportunity_authorized(
  p_prospect_id uuid,p_title text,p_catalog_item_id uuid default null,
  p_human_confirmation boolean default false
)
returns uuid language plpgsql security definer set search_path=public,pg_temp
as $$
declare v_id uuid; v_existing uuid;
  v_prospect public.prospects%rowtype;
begin
  if not public.has_prospect_management() then raise exception 'PROSPECT_MANAGEMENT_REQUIRED' using errcode='42501'; end if;
  if p_human_confirmation is not true then raise exception 'PROSPECT_HUMAN_CONFIRMATION_REQUIRED' using errcode='22023'; end if;
  if nullif(btrim(p_title),'') is null then raise exception 'OPPORTUNITY_TITLE_REQUIRED' using errcode='22023'; end if;
  select * into v_prospect from public.prospects p
    where p.id=p_prospect_id for update;
  if not found or v_prospect.archived_at is not null then raise exception 'PROSPECT_NOT_CONVERTIBLE' using errcode='22023'; end if;
  select id into v_existing from public.opportunities where prospect_id=p_prospect_id limit 1;
  if v_existing is not null then
    if v_prospect.status is distinct from 'converted' then
      update public.prospects set status='converted',converted_at=coalesce(converted_at,now()),updated_at=now()
        where id=p_prospect_id;
    end if;
    insert into public.radar_items(source_type,source_id,responsible_id,state,next_action,next_review_at,
      condition_text,last_movement_at,updated_at)
    select 'opportunity',v_existing,r.responsible_id,'active',r.next_action,r.next_review_at,
      r.condition_text,r.last_movement_at,now()
    from public.radar_items r
    where r.source_type='prospect' and r.source_id=p_prospect_id and r.state='active'
    on conflict (source_type,source_id) where state='active'
    do update set responsible_id=excluded.responsible_id,next_action=excluded.next_action,
      next_review_at=excluded.next_review_at,condition_text=excluded.condition_text,
      last_movement_at=excluded.last_movement_at,updated_at=now();
    update public.radar_items set state='closed',closed_at=now(),updated_at=now()
      where source_type='prospect' and source_id=p_prospect_id and state='active';
    return v_existing;
  end if;
  if v_prospect.status is distinct from 'qualifying' then raise exception 'PROSPECT_NOT_CONVERTIBLE' using errcode='22023'; end if;
  if not exists(select 1 from public.prospect_needs n where n.prospect_id=p_prospect_id and n.service_description<>'') then
    raise exception 'PROSPECT_NEED_REQUIRED' using errcode='22023'; end if;
  if not exists(select 1 from public.prospects p where p.id=p_prospect_id and p.next_action is not null
    and (p.next_review_at is not null or p.next_condition is not null)) then
    raise exception 'PROSPECT_CONTINUITY_REQUIRED' using errcode='22023'; end if;
  v_id:=public.convert_prospect_to_opportunity(p_prospect_id,btrim(p_title),p_catalog_item_id,null,null);
  insert into public.radar_items(source_type,source_id,responsible_id,state,next_action,next_review_at,
    condition_text,last_movement_at,updated_at)
  select 'opportunity',v_id,r.responsible_id,'active',r.next_action,r.next_review_at,
    r.condition_text,r.last_movement_at,now()
  from public.radar_items r
  where r.source_type='prospect' and r.source_id=p_prospect_id and r.state='active'
  on conflict (source_type,source_id) where state='active'
  do update set responsible_id=excluded.responsible_id,next_action=excluded.next_action,
    next_review_at=excluded.next_review_at,condition_text=excluded.condition_text,
    last_movement_at=excluded.last_movement_at,updated_at=now();
  update public.radar_items set state='closed',closed_at=now(),updated_at=now()
    where source_type='prospect' and source_id=p_prospect_id and state='active';
  return v_id;
end;
$$;
revoke all on function public.convert_prospect_to_opportunity_authorized(uuid,text,uuid,boolean) from public, anon, authenticated;
grant execute on function public.convert_prospect_to_opportunity_authorized(uuid,text,uuid,boolean) to authenticated;

