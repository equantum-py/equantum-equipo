alter table public.prospects
  add column if not exists source_other text,
  add column if not exists created_by uuid references public.profiles(id) on delete set null,
  add column if not exists updated_at timestamptz not null default now(),
  add column if not exists referrer_id uuid references public.profiles(id) on delete set null,
  add column if not exists last_contact_at timestamptz,
  add column if not exists customer_statement text,
  add column if not exists commercial_perception text,
  add column if not exists next_action text,
  add column if not exists next_review_at timestamptz,
  add column if not exists next_condition text,
  add column if not exists pause_reason text,
  add column if not exists pause_until timestamptz,
  add column if not exists closed_reason text;

alter table public.prospects
  add constraint prospects_doc08_status_check
  check (status in ('new','contacted','qualifying','converted','paused','disqualified'))
  not valid;
alter table public.prospects
  add constraint prospects_disqualified_reason_check
  check (status <> 'disqualified' or nullif(btrim(closed_reason),'') is not null)
  not valid;
alter table public.prospects
  add constraint prospects_paused_reason_check
  check (status <> 'paused' or nullif(btrim(pause_reason),'') is not null)
  not valid;

create table if not exists public.commercial_user_permissions (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  manage_prospects boolean not null default false,
  granted_by uuid references public.profiles(id) on delete set null,
  granted_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint commercial_permission_grant_audit_check
    check ((manage_prospects = false) or (granted_by is not null and granted_at is not null))
);

create table if not exists public.prospect_needs (
  id uuid primary key default gen_random_uuid(),
  prospect_id uuid not null references public.prospects(id) on delete cascade,
  catalog_item_id uuid references public.catalog_items(id) on delete set null,
  category text,
  service_description text not null,
  catalog_label_snapshot text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint prospect_need_description_nonempty check (length(btrim(service_description)) > 0)
);
create index if not exists prospect_needs_prospect_idx on public.prospect_needs(prospect_id, created_at);

-- Supports the DOC08 identity invariant without cloning a person's identity
-- for every company. The interface can remain simple while the model is N:N.
create table if not exists public.commercial_entity_contacts (
  company_entity_id uuid not null references public.commercial_entities(id) on delete restrict,
  person_entity_id uuid not null references public.commercial_entities(id) on delete restrict,
  relationship text,
  is_primary boolean not null default false,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key(company_entity_id, person_entity_id),
  constraint commercial_entity_contact_not_self check (company_entity_id <> person_entity_id)
);

create or replace function public.validate_commercial_entity_contact()
returns trigger language plpgsql set search_path = public, pg_temp as $$
begin
  if not exists (select 1 from public.commercial_entities where id=new.company_entity_id and entity_type='company')
     or not exists (select 1 from public.commercial_entities where id=new.person_entity_id and entity_type='person') then
    raise exception 'COMMERCIAL_CONTACT_ENTITY_TYPES_INVALID' using errcode='22023';
  end if;
  return new;
end;
$$;
revoke all on function public.validate_commercial_entity_contact() from public, anon, authenticated;
drop trigger if exists trg_validate_commercial_entity_contact on public.commercial_entity_contacts;
create trigger trg_validate_commercial_entity_contact
before insert or update on public.commercial_entity_contacts
for each row execute function public.validate_commercial_entity_contact();

create table if not exists public.prospect_events (
  id bigint generated by default as identity primary key,
