create or replace function public.guard_prospect_stage_change()
returns trigger language plpgsql security definer
set search_path=public,pg_temp
as $$
begin
  if new.status='converted' then
    if tg_op='INSERT' then
      if not exists(select 1 from public.opportunities o where o.prospect_id=new.id) then
        raise exception 'PROSPECT_CONVERSION_FUNCTION_REQUIRED' using errcode='42501';
      end if;
    elsif old.status is distinct from 'converted' then
      if not exists(select 1 from public.opportunities o where o.prospect_id=new.id) then
        raise exception 'PROSPECT_CONVERSION_FUNCTION_REQUIRED' using errcode='42501';
      end if;
    end if;
  end if;
  return new;
end;
$$;
revoke all on function public.guard_prospect_stage_change() from public,anon,authenticated;
drop trigger if exists trg_guard_prospect_stage_change on public.prospects;
create trigger trg_guard_prospect_stage_change before insert or update on public.prospects
for each row execute function public.guard_prospect_stage_change();

